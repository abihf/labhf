# Falco for k3s, pinned to the release the image's falco.ko was built for
# (falco-build stage), so module and Falco only change together, in one
# `bootc upgrade`. Into /out (copied into rootfs):
#   /usr/share/labhf/k3s-charts/falco-<chart>.tgz   the chart (ADD --checksum);
#       labhf-k3s-manifests.service links it into k3s's static/charts
#   /usr/share/labhf/k3s-manifests/falco.yaml       HelmChart for that file,
#       Falco image by digest, kmod driver, no driver loader
# /in (falco-chart-src stage): falco.tgz, driver.cmake (Falco's, at FALCO_VERSION)
set -euxo pipefail

falco=${FALCO_VERSION:?} chart=${FALCO_CHART_VERSION:?} digest=${FALCO_IMAGE_DIGEST:?}
dver=${FALCO_DRIVER_VERSION:?} libs_sha=${FALCO_LIBS_SHA256:?}

# The chart deploys this Falco release...
tar -xzOf /in/falco.tgz falco/Chart.yaml > /tmp/Chart.yaml
grep -qx "version: ${chart}" /tmp/Chart.yaml
grep -qx "appVersion: ${falco}" /tmp/Chart.yaml
# ...and this Falco release needs the driver falco-build built (it refuses to
# start on another API/schema version: k3s would run without it, unnoticed)
grep -q "set(DRIVER_VERSION \"${dver}\")" /in/driver.cmake ||
    { echo "Falco ${falco} doesn't use driver ${dver}:" >&2; grep -A3 'NOT DRIVER_VERSION' /in/driver.cmake >&2; exit 1; }
grep -q "\"SHA256=${libs_sha}\"" /in/driver.cmake ||
    { echo "FALCO_LIBS_SHA256 is not Falco ${falco}'s DRIVER_CHECKSUM" >&2; exit 1; }
[[ $digest =~ ^sha256:[0-9a-f]{64}$ ]]

install -D -m 0644 /in/falco.tgz "/out/usr/share/labhf/k3s-charts/falco-${chart}.tgz"
install -d /out/usr/share/labhf/k3s-manifests
cat > /out/usr/share/labhf/k3s-manifests/falco.yaml <<EOF
# Auto-applied by k3s (symlinked into /var/lib/rancher/k3s/server/manifests).
# Generated by build/falco-manifest.sh: Falco ${falco} (chart ${chart}), the
# release the image's falco.ko (driver ${dver}) is built for. The kmod is
# signed and loaded at boot (modules-load.d/labhf-falco.conf); the chart's
# driver loader would only fetch an unsigned one. Machine-local values: a
# HelmChartConfig "falco" in kube-system (keep image and driver as they are).
# Opt out: \`disable: [labhf-falco]\` in /etc/rancher/k3s/config.yaml.d/*.yaml
# (k3s then uninstalls the chart; the module stays loaded, idle).
apiVersion: helm.cattle.io/v1
kind: HelmChart
metadata:
  name: falco
  namespace: kube-system
spec:
  chart: https://%{KUBERNETES_API}%/static/charts/falco-${chart}.tgz
  targetNamespace: falco
  createNamespace: true
  valuesContent: |-
    image:
      tag: "${falco}@${digest}"
    driver:
      kind: kmod
      loader:
        enabled: false
EOF
# fixed mtime, like the other files the build installs itself (see k3s.sh)
touch -d @0 /out/usr/share/labhf/k3s-charts/falco-"${chart}".tgz /out/usr/share/labhf/k3s-manifests/falco.yaml
cat /out/usr/share/labhf/k3s-manifests/falco.yaml
